
.MODEL SMALL
.STACK 100H

.DATA
    BCD DB 25H

    ASCII_TENS DB ?
    ASCII_UNITS DB ?

.CODE
MAIN PROC

    MOV AX, @DATA
    MOV DS, AX

    ; EXTRACT TENS DIGIT
    MOV AL, BCD
    AND AL, 0F0H
    MOV CL, 04H
    SHR AL, CL
    ADD AL, 30H
    MOV ASCII_TENS, AL

    ; EXTRACT UNITS DIGIT
    MOV AL, BCD
    AND AL, 0FH
    ADD AL, 30H
    MOV ASCII_UNITS, AL

    MOV AH, 4CH
    INT 21H

MAIN ENDP
END MAIN
