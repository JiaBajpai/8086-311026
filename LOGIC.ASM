
.MODEL SMALL
.STACK 100H

.DATA
    NUM1 DB 12H
    NUM2 DB 0AH

    RESULT_AND DB ?
    RESULT_OR  DB ?
    RESULT_XOR DB ?
    RESULT_NOT DB ?

.CODE
MAIN PROC

    MOV AX, @DATA
    MOV DS, AX

    ; AND OPERATION
    MOV AL, NUM1
    AND AL, NUM2
    MOV RESULT_AND, AL

    ; OR OPERATION
    MOV AL, NUM1
    OR AL, NUM2
    MOV RESULT_OR, AL

    ; XOR OPERATION
    MOV AL, NUM1
    XOR AL, NUM2
    MOV RESULT_XOR, AL

    ; NOT OPERATION
    MOV AL, NUM1
    NOT AL
    MOV RESULT_NOT, AL

    MOV AH, 4CH
    INT 21H

MAIN ENDP
END MAIN
